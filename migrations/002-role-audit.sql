CREATE TABLE IF NOT EXISTS postcheck_role_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id text NOT NULL, target_id text NOT NULL, old_role text NOT NULL,
 new_role text NOT NULL, reason text NOT NULL CHECK(length(reason) BETWEEN 8 AND 500),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS postcheck_role_audit_created_idx ON postcheck_role_audit(created_at DESC,id DESC);
REVOKE ALL ON postcheck_role_audit FROM PUBLIC;
